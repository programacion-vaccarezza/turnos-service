CREATE TABLE reservation_process (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_login             VARCHAR(100) NOT NULL,
    professional_id         BIGINT       NOT NULL,
    appointment_date        DATE         NOT NULL,
    start_time              TIME         NOT NULL,
    patient_first_name      VARCHAR(100) NOT NULL,
    patient_last_name       VARCHAR(100) NOT NULL,
    status                  VARCHAR(30)  NOT NULL,
    hold_id                 VARCHAR(100),
    reservation_process_id  VARCHAR(100),
    expires_at              TIMESTAMP WITH TIME ZONE,
    request_event_id        VARCHAR(100),
    reservation_id          BIGINT,
    failure_reason          VARCHAR(500),
    created_at              TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at              TIMESTAMP WITH TIME ZONE NOT NULL,
    version                 BIGINT       NOT NULL,

    CONSTRAINT uk_reservation_process_reservation_process_id UNIQUE (reservation_process_id)
);

CREATE INDEX idx_reservation_process_owner_login ON reservation_process (owner_login);
